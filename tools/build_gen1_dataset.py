for p in pokemon_list:
    name = p['name']
    zy_parts = [zhuyin_char_map.get(ch, '') for ch in name]
    p['zhuyin'] = ' '.join(zy_parts)
    
    # Evolution info
    pid = p['id']
    if pid in evolution_rules:
        rule = evolution_rules[pid]
        target_p = next((x for x in pokemon_list if x['id'] == rule['to']), None)
        p['evolution'] = {
            'reqLevel': rule['evolvesAt'],
            'evolvesToId': rule['to'],
            'evolvesToName': target_p['name'] if target_p else ''
        }
    else:
        p['evolution'] = None

    # Signature move
    moves = signature_moves.get(p['primaryType'], ['撞擊'])
    p['move'] = moves[(pid % len(moves))]

    # Description
    p['desc'] = f"全國圖鑑 No.{pid:03d}，來自關都地區的經典寶可夢！屬性為【{'/'.join(p['types'])}】。"

